// Generates docs/data-dictionary-columns.md from the Prisma schema.
// No dependencies. Run from anywhere:
//   node fgae-ims-database/tools/generate-data-dictionary.mjs
// Optional: pass another schema path as the first argument.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(process.argv[2] ?? resolve(here, '../../fgae-ims-backend/prisma/schema.prisma'));
const outPath = resolve(here, '../docs/data-dictionary-columns.md');

// Order and grouping of the tables in the document. A table that is not listed
// here still appears, at the end, under "Other": add it to the right group.
const DOMAINS = [
  ['Organization structure', ['organizations', 'areas', 'branches', 'health_facilities']],
  ['Accounts, roles and access', ['users', 'user_credentials', 'user_sessions', 'account_activation_tokens', 'roles', 'permissions', 'role_permissions', 'user_roles', 'organizational_assignments']],
  ['People, applications and volunteers', ['persons', 'departments', 'volunteer_applications', 'application_documents', 'payments', 'volunteers', 'volunteer_number_counters', 'notifications', 'skills', 'application_skills', 'volunteer_skills', 'interests', 'application_interests', 'volunteer_interests', 'system_settings']],
  ['Programs, projects and budgets', ['programs', 'projects', 'project_budget_allocations']],
  ['Field operations', ['volunteer_assignments', 'volunteer_attendance']],
  ['Allowances and payouts', ['allowance_requests', 'allowance_disbursements']],
  ['Audit', ['audit_logs']],
];
const PARTITIONED = { volunteer_attendance: 'Partitioned monthly by `activityDate` (hand-written SQL: Prisma cannot declare partitions).' };

const src = readFileSync(schemaPath, 'utf8').replace(/\r/g, '');

// ---- parse -----------------------------------------------------------------
const enums = {};
for (const m of src.matchAll(/^enum (\w+) \{([\s\S]*?)^\}/gm)) {
  enums[m[1]] = m[2].split('\n').map(l => l.split('//')[0].trim()).filter(Boolean);
}
const models = {};
for (const m of src.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) models[m[1]] = m[2];

const tableOf = name => /@@map\("([^"]+)"\)/.exec(models[name])?.[1] ?? name;
const cols = list => list.split(',').map(s => s.trim());
const FK_ACTION = { Restrict: 'RESTRICT', Cascade: 'CASCADE', SetNull: 'SET NULL', NoAction: 'NO ACTION' };

function sqlType(base, attrs) {
  const db = /@db\.(\w+)(?:\(([^)]*)\))?/.exec(attrs);
  if (db) {
    const [, t, a] = db;
    return ({ Uuid: 'UUID', Text: 'TEXT', Date: 'DATE' })[t]
      ?? ({ VarChar: `VARCHAR(${a})`, Timestamptz: `TIMESTAMPTZ(${a})`, Time: `TIME(${a})`, Decimal: `DECIMAL(${a})` })[t]
      ?? `${t}${a ? `(${a})` : ''}`;
  }
  return ({ String: 'TEXT', DateTime: 'TIMESTAMP(3)', Int: 'INTEGER', Boolean: 'BOOLEAN', Json: 'JSONB', Decimal: 'DECIMAL(65,30)', BigInt: 'BIGINT', Float: 'DOUBLE PRECISION' })[base] ?? base;
}

const tables = {}; // table name -> info
for (const [model, body] of Object.entries(models)) {
  const t = { model, name: tableOf(model), columns: [], fks: [], uniques: [], indexes: [], pk: [] };
  for (const raw of body.split('\n')) {
    const line = raw.split('//')[0].trim();
    if (!line || line.startsWith('@@')) continue;
    const mm = /^(\w+)\s+(\w+)(\[\]|\?)?\s*(.*)$/.exec(line);
    if (!mm) continue;
    const [, field, type, mod, attrs] = mm;
    if (mod === '[]') continue;                       // back-reference list, no column
    if (models[type]) {                                // relation: records the foreign key
      const rel = /@relation\((?:"[^"]*",\s*)?fields:\s*\[([^\]]+)\],\s*references:\s*\[([^\]]+)\](.*)\)/.exec(attrs);
      if (rel) {
        const od = /onDelete:\s*(\w+)/.exec(rel[3])?.[1];
        t.fks.push({ from: cols(rel[1]), toModel: type, to: cols(rel[2]), onDelete: FK_ACTION[od] ?? (mod === '?' ? 'SET NULL' : 'RESTRICT') });
      }
      continue;
    }
    const isEnum = type in enums;
    const def = /@default\(((?:[^()]|\([^)]*\))*)\)/.exec(attrs)?.[1];
    let dflt = '';
    if (def === 'uuid()' || def === 'cuid()') dflt = 'none (generated by Prisma)';
    else if (def === 'now()') dflt = 'CURRENT_TIMESTAMP';
    else if (def !== undefined) dflt = def.replace(/^"|"$/g, "'").replace(/^'|'$/g, '');
    else if (/@updatedAt/.test(attrs)) dflt = 'none (set by Prisma)';
    t.columns.push({ name: field, type: isEnum ? `enum ${type}` : sqlType(type, attrs), nullable: mod === '?', dflt, isPk: /@id\b/.test(attrs), isUnique: /@unique\b/.test(attrs) });
  }
  const id = /@@id\(\[([^\]]+)\]/.exec(body); if (id) t.pk = cols(id[1]);
  t.pk = t.pk.length ? t.pk : t.columns.filter(c => c.isPk).map(c => c.name);
  for (const m of body.matchAll(/@@unique\(\[([^\]]+)\]/g)) t.uniques.push(cols(m[1]));
  for (const m of body.matchAll(/@@index\(\[([^\]]+)\]/g)) t.indexes.push(cols(m[1]));
  tables[t.name] = t;
}
const byModel = Object.fromEntries(Object.values(tables).map(t => [t.model, t]));
const referencedBy = Object.fromEntries(Object.keys(tables).map(n => [n, []]));
for (const t of Object.values(tables)) for (const fk of t.fks) referencedBy[byModel[fk.toModel].name].push(`${t.name}(${fk.from.join(', ')})`);

// ---- render ----------------------------------------------------------------
const esc = s => String(s).replace(/\|/g, '\\|');
const out = [];
const used = new Set();
const groups = DOMAINS.map(([title, names]) => [title, names.filter(n => n in tables)]);
const listed = new Set(DOMAINS.flatMap(([, n]) => n));
const other = Object.keys(tables).filter(n => !listed.has(n));
if (other.length) groups.push(['Other (add these to DOMAINS in the generator)', other]);

out.push('# FGAE-IMS data dictionary: columns and keys', '');
out.push('> **Generated file. Do not edit by hand.** It is rebuilt from `fgae-ims-backend/prisma/schema.prisma` by `fgae-ims-database/tools/generate-data-dictionary.mjs`.');
out.push('> Purposes, business rules and open decisions are in [data-dictionary.md](data-dictionary.md).', '');
out.push(`**${Object.keys(tables).length} tables, ${Object.keys(enums).length} enums.**`, '');
out.push('## Contents', '');
for (const [title, names] of groups) out.push(`- **${title}:** ` + names.map(n => `[${n}](#${n.replace(/_/g, '_')})`).join(', '));
out.push('', '## How to read the columns', '');
out.push('- **Default "none (generated by Prisma)"** means the database has no default: the backend creates the UUID. Raw SQL inserts must supply `id` (use `gen_random_uuid()`).');
out.push('- **Default "none (set by Prisma)"** is the same for `updatedAt`: raw SQL inserts must supply it (use `now()`).');
out.push('- **ON DELETE RESTRICT** means a row cannot be deleted while others point to it, so history stays intact. CASCADE deletes the dependent rows too. SET NULL clears the link.', '');

for (const [title, names] of groups) {
  out.push(`## ${title}`, '');
  for (const n of names) {
    const t = tables[n]; used.add(n);
    out.push(`### ${n}`, '');
    out.push(`Prisma model: \`${t.model}\`. Primary key: ${t.pk.map(c => `\`${c}\``).join(' + ') || '(none)'}.` + (PARTITIONED[n] ? ` ${PARTITIONED[n]}` : ''), '');
    const fkByCol = {};
    for (const fk of t.fks) fk.from.forEach((c, i) => { (fkByCol[c] ??= []).push(`→ \`${tables[byModel[fk.toModel].name].name}.${fk.to[i]}\` (ON DELETE ${fk.onDelete})`); });
    out.push('| Column | Type | Null | Default | Key / reference |', '|---|---|---|---|---|');
    for (const c of t.columns) {
      const key = [];
      if (t.pk.includes(c.name)) key.push(t.pk.length > 1 ? 'PK (part)' : 'PK');
      if (c.isUnique) key.push('UNIQUE');
      key.push(...(fkByCol[c.name] ?? []));
      out.push(`| \`${c.name}\` | ${esc(c.type)} | ${c.nullable ? 'yes' : 'no'} | ${esc(c.dflt) || ''} | ${esc(key.join('; '))} |`);
    }
    out.push('');
    const extra = [];
    for (const u of t.uniques) extra.push(`- Unique together: ${u.map(c => `\`${c}\``).join(' + ')}`);
    for (const i of t.indexes) extra.push(`- Index: ${i.map(c => `\`${c}\``).join(' + ')}`);
    if (extra.length) out.push(...extra, '');
    if (referencedBy[n].length) out.push(`Referenced by: ${referencedBy[n].map(x => `\`${x}\``).join(', ')}`, '');
  }
}
out.push('## Enums', '');
out.push('| Enum | Values |', '|---|---|');
for (const [e, v] of Object.entries(enums)) out.push(`| \`${e}\` | ${v.map(x => `\`${x}\``).join(', ')} |`);
out.push('', '## Rules that Prisma cannot express', '');
out.push('The schema file does not show these; they are hand-written SQL in the migrations (see [data-dictionary.md](data-dictionary.md), section "Rules enforced by the database"): partitions, CHECK constraints, the payout-ledger triggers, the one-active-role index, and Row Level Security.', '');
writeFileSync(outPath, out.join('\n'));
console.log(`Wrote ${outPath}\n${Object.keys(tables).length} tables, ${Object.values(tables).reduce((a, t) => a + t.columns.length, 0)} columns, ${Object.keys(enums).length} enums.` + (other.length ? `\nNot in DOMAINS: ${other.join(', ')}` : ''));
