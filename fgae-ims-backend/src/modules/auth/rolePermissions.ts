
import { PERMISSIONS } from "./permissions.js";
import type { Permission } from "./permissions.js";

export const ROLES = {
  SUPER_ADMIN: "SUPER_ADMIN",
  AREA_MANAGER: "AREA_MANAGER",
  PROJECT_MANAGER: "PROJECT_MANAGER",
  BRANCH_MANAGER: "BRANCH_MANAGER",
  VOLUNTEER_MANAGER: "VOLUNTEER_MANAGER",
  FIELD_SUPERVISOR: "FIELD_SUPERVISOR",
  HR_OFFICER: "HR_OFFICER",
  FINANCE_OFFICER: "FINANCE_OFFICER",
  VOLUNTEER: "VOLUNTEER",
} as const;

export type Role = (typeof ROLES)[keyof typeof ROLES];

export const ROLE_PERMISSIONS: Record<
  Role,
  readonly Permission[]
> = {
  SUPER_ADMIN: Object.values(PERMISSIONS),

  AREA_MANAGER: [
    PERMISSIONS.PROJECT_READ,
    PERMISSIONS.PROJECT_APPROVE,
    PERMISSIONS.FINANCE_READ,
    PERMISSIONS.FINANCE_BUDGET_MANAGE,
    PERMISSIONS.PROJECT_ALLOWANCE_APPROVE,
  ],

  PROJECT_MANAGER: [
    PERMISSIONS.PROJECT_READ,
    PERMISSIONS.PROJECT_CREATE,
    PERMISSIONS.PROJECT_UPDATE,
    PERMISSIONS.PROJECT_ALLOWANCE_REQUEST,
  ],

  BRANCH_MANAGER: [],

  VOLUNTEER_MANAGER: [
    PERMISSIONS.VOLUNTEER_READ,
    PERMISSIONS.VOLUNTEER_CREATE,
    PERMISSIONS.VOLUNTEER_UPDATE,
    PERMISSIONS.VOLUNTEER_APPROVE,
  ],

  FIELD_SUPERVISOR: [
    PERMISSIONS.VOLUNTEER_READ,
    PERMISSIONS.VOLUNTEER_ALLOWANCE_APPROVE,
  ],

  HR_OFFICER: [
    PERMISSIONS.HR_READ,
  ],

  FINANCE_OFFICER: [
    PERMISSIONS.FINANCE_READ,
    PERMISSIONS.FINANCE_PAYMENT_PROCESS,
  ],

  VOLUNTEER: [
    PERMISSIONS.VOLUNTEER_ALLOWANCE_REQUEST,
  ],
};

export const roleHasPermission = (
  role: Role,
  permission: Permission
): boolean => {
  return ROLE_PERMISSIONS[role].includes(permission);
};
