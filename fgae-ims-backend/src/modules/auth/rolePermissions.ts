// Check whether a predefined role has a permission.
export const roleHasDefaultPermission = (
  role: BuiltInRole,
  permission: Permission
): boolean => {
  return DEFAULT_ROLE_PERMISSIONS[role].includes(permission);
};

export const roleHasPermission = (
  role: Role,
  permission: Permission
): boolean => {
  return roleHasDefaultPermission(role, permission);
};

