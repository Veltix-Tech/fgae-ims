import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { en } from '../src/i18n/locales/en/auth'
import { am } from '../src/i18n/locales/am/auth'

for (const locale of ['en', 'am'] as const) {
  const copy = locale === 'en' ? en : am
  for (const width of [360, 390, 768, 1024, 1440]) {
    test(`recovery ${locale} ${width}px validation, confirmation and accessibility`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 })
      await page.goto('/forgot-password')
      await page.locator('#language').click()
      await page.locator('#language-options').getByRole('button', { name: locale === 'en' ? 'English' : 'አማርኛ', exact: true }).click()
      await expect(page).toHaveTitle(copy.recoveryTitle)
      await page.evaluate(() => document.fonts.ready)
      await page.screenshot({ path: `docs/screenshots/recovery-${locale}-${width}.png`, fullPage: true, animations: 'disabled' })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
      await page.getByRole('button', { name: copy.recoverySubmit, exact: true }).click()
      await expect(page.locator('#recovery-email')).toBeFocused()
      await expect(page.getByText(copy.emailRequired, { exact: true })).toBeVisible()
      await page.locator('#recovery-email').fill('invalid')
      await page.getByRole('button', { name: copy.recoverySubmit, exact: true }).click()
      await expect(page.getByText(copy.emailInvalid, { exact: true })).toBeVisible()
      await page.locator('#recovery-email').fill('unknown@example.test')
      await page.getByRole('button', { name: copy.recoverySubmit, exact: true }).click()
      await expect(page.getByRole('heading', { name: copy.recoveryReceived })).toBeFocused()
      await expect(page.getByText(copy.recoveryConfirmation, { exact: true })).toBeVisible()
      await expect(page.getByRole('button', { name: copy.recoveryResend })).toBeDisabled()
      await page.screenshot({ path: `docs/screenshots/recovery-confirmation-${locale}-${width}.png`, fullPage: true, animations: 'disabled' })
      expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()).violations).toEqual([])
      if (locale === 'am') expect(await page.locator('body').innerText()).not.toContain('።')
    })
  }
  test(`recovery ${locale} refresh, resend, change email and offline retry`, async ({ page, context }) => {
    await page.clock.install()
    await page.goto('/forgot-password')
    await page.locator('#language').click()
    await page.locator('#language-options').getByRole('button', { name: locale === 'en' ? 'English' : 'አማርኛ', exact: true }).click()
    await page.locator('#recovery-email').fill('volunteer@example.test')
    await context.setOffline(true)
    await page.getByRole('button', { name: copy.recoverySubmit }).click()
    await expect(page.getByRole('alert')).toContainText(copy.NETWORK)
    await expect(page.getByRole('alert')).toBeFocused()
    await expect(page.locator('#recovery-email')).toHaveValue('volunteer@example.test')
    await context.setOffline(false)
    await page.getByRole('button', { name: copy.recoverySubmit }).click()
    await expect(page.getByRole('heading', { name: copy.recoveryReceived })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: copy.recoveryReceived })).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('lang', locale)
    await page.clock.fastForward(61_000)
    await page.getByRole('button', { name: copy.recoveryResend }).click()
    await expect.poll(async () => page.evaluate(() => JSON.parse(sessionStorage.getItem('fgae.synthetic.recovery.requests.v1')!).requests.length)).toBe(2)
    await page.getByRole('button', { name: copy.recoveryChange }).click()
    await expect(page.locator('#recovery-email')).toBeFocused()
    await page.locator('#recovery-email').fill('different@example.test')
    await page.clock.fastForward(61_000)
    await page.getByRole('button', { name: copy.recoverySubmit }).click()
    await expect(page.getByText('different@example.test', { exact: true })).toBeVisible()
  })
}

test('sign-in recovery navigation, keyboard, language preserves entry and reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/sign-in')
  await page.getByRole('link', { name: en.forgotPassword }).click()
  await expect(page).toHaveURL(/\/forgot-password$/)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: en.recoverySkip })).toBeFocused()
  await page.keyboard.press('Enter'); await expect(page.locator('#recovery-heading')).toBeFocused()
  await page.keyboard.press('Tab'); await expect(page.locator('#recovery-email')).toBeFocused()
  await page.keyboard.type('retained@example.test')
  await page.locator('#language').click()
  await page.getByRole('button', { name: 'አማርኛ', exact: true }).click()
  await expect(page.locator('#recovery-email')).toHaveValue('retained@example.test')
  await expect(page.locator('.form-panel')).toHaveCSS('animation-name', 'none')
  await page.getByRole('link', { name: am.recoveryBack }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await expect(page.getByRole('heading', { name: am.welcome })).toBeVisible()
})

test('live recovery loading, failed retry, idempotency, rate limit and generic success', async ({ page }) => {
  await page.clock.install()
  await page.goto('http://127.0.0.1:5174/forgot-password')
  const keys: string[] = []
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/auth/forgot-password', async route => {
    keys.push(route.request().headers()['idempotency-key']!)
    await gate
    await route.fulfill({ status: 503, json: { message: 'Never display backend internals' } })
  })
  await page.locator('#recovery-email').fill('test@example.test')
  await page.getByRole('button', { name: en.recoverySubmit }).click()
  await expect(page.getByRole('button', { name: en.recoverySubmitting })).toBeDisabled()
  release()
  await expect(page.getByRole('alert')).toContainText(en.recoveryUnavailable)
  await expect(page.locator('#recovery-email')).toHaveValue('test@example.test')
  await page.route('**/auth/forgot-password', async route => {
    keys.push(route.request().headers()['idempotency-key']!)
    await route.fulfill({ status: 429, headers: { 'Retry-After': '3' }, json: {} })
  })
  await page.getByRole('button', { name: en.recoverySubmit }).click()
  await expect(page.getByRole('alert')).toContainText(en.RATE_LIMITED)
  expect(keys[0]).toBe(keys[1])
  await expect(page.getByRole('button', { name: en.recoverySubmit })).toBeDisabled()
  await page.clock.fastForward(4000)
  await page.route('**/auth/forgot-password', route => route.fulfill({ status: 202, json: { success: true, data: { accepted: true, retry_after_seconds: 60 } } }))
  await page.getByRole('button', { name: en.recoverySubmit }).click()
  await expect(page.getByRole('heading', { name: en.recoveryReceived })).toBeFocused()
  await page.reload()
  await expect(page.getByRole('heading', { name: en.recoveryReceived })).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('fgae.synthetic.recovery.requests.v1'))).toBeNull()
})
