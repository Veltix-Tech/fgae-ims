import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { en } from '../src/i18n/locales/en/auth'
import { am } from '../src/i18n/locales/am/auth'

const newPassword = 'A new fictional phrase 2026'
async function chooseLanguage(page: Page, locale: 'en' | 'am') {
  await page.locator('#language').click()
  await page.locator('#language-options').getByRole('button', { name: locale === 'en' ? 'English' : 'አማርኛ', exact: true }).click()
}
for (const locale of ['en', 'am'] as const) {
  const copy = locale === 'en' ? en : am
  for (const width of [360, 390, 768, 1024, 1440]) {
    test(`reset ${locale} ${width}px validation, controls and success`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 })
      await page.goto('/reset-password#token=demo-reset-volunteer')
      await chooseLanguage(page, locale)
      await expect(page.getByRole('heading', { name: copy.resetHeading })).toBeVisible()
      await expect(page).toHaveURL(/\/reset-password$/)
      await expect(page).toHaveTitle(copy.resetTitle)
      await page.evaluate(() => document.fonts.ready)
      await page.screenshot({ path: `docs/screenshots/reset-${locale}-${width}.png`, fullPage: true, animations: 'disabled' })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
      await page.getByRole('button', { name: copy.resetSubmit }).click()
      await expect(page.locator('#new-password')).toBeFocused()
      await page.locator('#new-password').fill('short')
      await page.getByRole('button', { name: copy.resetSubmit }).click()
      await expect(page.getByText(copy.resetLength, { exact: true })).toBeVisible()
      await page.locator('#new-password').fill(newPassword)
      await page.locator('#confirm-password').fill('mismatch')
      await page.getByRole('button', { name: copy.resetSubmit }).click()
      await expect(page.locator('#confirm-password')).toBeFocused()
      await expect(page.getByText(copy.resetMismatch, { exact: true })).toBeVisible()
      await page.getByRole('button', { name: copy.resetShowNew }).click()
      await expect(page.locator('#new-password')).toHaveAttribute('type', 'text')
      await page.getByRole('button', { name: copy.resetShowConfirm }).click()
      await expect(page.locator('#confirm-password')).toHaveAttribute('type', 'text')
      await page.locator('#confirm-password').fill(newPassword)
      await page.getByRole('button', { name: copy.resetSubmit }).click()
      await expect(page.getByRole('heading', { name: copy.resetSuccessHeading })).toBeFocused()
      await expect(page.locator('input[type="password"]')).toHaveCount(0)
      await page.screenshot({ path: `docs/screenshots/reset-success-${locale}-${width}.png`, fullPage: true, animations: 'disabled' })
      expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()).violations).toEqual([])
      if (locale === 'am') expect(await page.locator('body').innerText()).not.toContain('።')
    })
  }
  test(`reset ${locale} missing, invalid, expired and used links`, async ({ page }) => {
    await page.goto('/reset-password')
    await chooseLanguage(page, locale)
    await expect(page.getByRole('heading', { name: copy.resetMissingHeading })).toBeVisible()
    for (const [token, heading] of [['invalid-link', copy.resetInvalidHeading], ['demo-reset-expired', copy.resetExpiredHeading], ['demo-reset-used', copy.resetUsedHeading]]) {
      await page.goto(`/reset-password#token=${token}`)
      await expect(page.getByRole('heading', { name: heading })).toBeVisible()
      await expect(page.locator('#new-password')).toHaveCount(0)
      await expect(page.getByRole('link', { name: copy.resetRequestLink })).toHaveAttribute('href', '/forgot-password')
    }
  })
  test(`reset ${locale} full recovery journey, persistent password and previous session invalidation`, async ({ page, context }) => {
    await page.goto('/sign-in')
    await chooseLanguage(page, locale)
    await page.locator('#email').fill('volunteer@example.test')
    await page.locator('#password').fill('Demo-only-2026!')
    await page.getByRole('button', { name: copy.signIn, exact: true }).click()
    await expect(page.getByRole('heading', { name: copy.signedIn })).toBeVisible()
    const resetPage = await context.newPage()
    await resetPage.goto('/forgot-password')
    await resetPage.locator('#recovery-email').fill('volunteer@example.test')
    await resetPage.getByRole('button', { name: copy.recoverySubmit }).click()
    await expect(resetPage.getByRole('heading', { name: copy.recoveryReceived })).toBeVisible()
    // Synthetic delivery lives outside the workplace UI; this exercises the request-created link.
    const link = await resetPage.evaluate(() => JSON.parse(localStorage.getItem('fgae.synthetic.credentials.v1')!).links.at(-1).token as string)
    await resetPage.goto(`/reset-password#token=${link}`)
    await resetPage.locator('#new-password').fill(newPassword)
    await resetPage.locator('#confirm-password').fill(newPassword)
    await resetPage.getByRole('button', { name: copy.resetSubmit }).click()
    await expect(resetPage.getByRole('heading', { name: copy.resetSuccessHeading })).toBeVisible()
    await page.bringToFront()
    await expect(page.getByRole('heading', { name: copy.welcome })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: copy.welcome })).toBeVisible()
    await resetPage.bringToFront()
    await resetPage.getByRole('link', { name: copy.resetSignIn }).click()
    await resetPage.locator('#email').fill('volunteer@example.test')
    await resetPage.locator('#password').fill('Demo-only-2026!')
    await resetPage.getByRole('button', { name: copy.signIn, exact: true }).click()
    await expect(resetPage.getByRole('alert')).toContainText(copy.INVALID_CREDENTIALS)
    await resetPage.locator('#password').fill(newPassword)
    await resetPage.getByRole('button', { name: copy.signIn, exact: true }).click()
    await expect(resetPage.getByRole('heading', { name: copy.signedIn })).toBeVisible()
    await resetPage.reload()
    await expect(resetPage.getByRole('heading', { name: copy.signedIn })).toBeVisible()
    await resetPage.goto(`/reset-password#token=${link}`)
    await expect(resetPage.getByRole('heading', { name: copy.resetUsedHeading })).toBeVisible()
  })
}

test('reset language retains values, offline retry, unsaved changes and refresh cleanup', async ({ page, context }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/reset-password#token=demo-reset-volunteer')
  await page.locator('#new-password').fill(newPassword)
  await page.locator('#confirm-password').fill(newPassword)
  await chooseLanguage(page, 'am')
  await expect(page.locator('#new-password')).toHaveValue(newPassword)
  await expect(page.locator('.form-panel')).toHaveCSS('animation-name', 'none')
  await page.getByRole('link', { name: am.recoveryBack }).click()
  await expect(page.getByRole('heading', { name: am.resetLeaveHeading })).toBeFocused()
  await page.getByRole('button', { name: am.resetKeepEditing }).click()
  await expect(page.getByRole('link', { name: am.recoveryBack })).toBeFocused()
  await context.setOffline(true)
  await page.getByRole('button', { name: am.resetSubmit }).click()
  await expect(page.getByRole('alert')).toContainText(am.NETWORK)
  await expect(page.locator('#new-password')).toHaveValue(newPassword)
  await context.setOffline(false)
  await page.getByRole('link', { name: am.recoveryBack }).click()
  await page.getByRole('button', { name: am.resetDiscard }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/reset-password#token=demo-reset-volunteer')
  await expect(page.getByRole('heading', { name: am.resetHeading })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: am.resetMissingHeading })).toBeVisible()
})

test('live reset validation retry, busy submission, policy error and idempotent retry', async ({ page }) => {
  const origin = 'http://127.0.0.1:5174'
  await page.route('**/auth/reset-password/validate', route => route.fulfill({ status: 503, json: {} }))
  await page.goto(`${origin}/reset-password#token=live-test-only`)
  await expect(page.getByRole('heading', { name: en.resetCheckFailedHeading })).toBeVisible()
  await page.route('**/auth/reset-password/validate', route => route.fulfill({ json: { success: true, data: { valid: true, expires_at: new Date(Date.now() + 600_000).toISOString() } } }))
  await page.getByRole('button', { name: en.resetRetry }).click()
  await page.locator('#new-password').fill(newPassword)
  await page.locator('#confirm-password').fill(newPassword)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const keys: string[] = []
  await page.route('**/auth/reset-password', async route => {
    keys.push(route.request().headers()['idempotency-key']!)
    await gate; await route.fulfill({ status: 422, json: { code: 'PASSWORD_REJECTED' } })
  })
  await page.getByRole('button', { name: en.resetSubmit }).click()
  await expect(page.getByRole('button', { name: en.resetSubmitting })).toBeDisabled()
  release()
  await expect(page.getByRole('alert')).toContainText(en.resetRejected)
  await expect(page.locator('#new-password')).toHaveValue(newPassword)
  await page.route('**/auth/reset-password', async route => {
    keys.push(route.request().headers()['idempotency-key']!)
    await route.fulfill({ json: { success: true, data: { completed: true } } })
  })
  await page.getByRole('button', { name: en.resetSubmit }).click()
  await expect(page.getByRole('heading', { name: en.resetSuccessHeading })).toBeFocused()
  expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1])
  expect(await page.evaluate(() => localStorage.getItem('fgae.synthetic.credentials.v1'))).toBeNull()
})
