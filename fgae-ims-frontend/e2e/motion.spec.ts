import { test, expect } from '@playwright/test'

test('pointer and keyboard ripples clean up without changing form actions', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/sign-in')
  const reveal = page.getByRole('button', { name: 'Show password', exact: true })
  await expect(reveal).toBeVisible()
  await expect(page.locator('.welcome-panel')).toHaveCSS('animation-name', 'enter-up')
  await page.locator('#password').fill('retained-input')
  const bounds = await reveal.boundingBox()
  await page.mouse.move(bounds!.x + 12, bounds!.y + 12)
  await page.mouse.down()
  await expect(reveal.locator('.button-ripple')).toHaveCount(1)
  await expect(reveal.locator('.button-ripple')).toHaveAttribute('aria-hidden', 'true')
  await page.mouse.up()
  await expect(page.locator('#password')).toHaveAttribute('type', 'text')
  await expect(page.locator('.button-ripple')).toHaveCount(0)
  const hide = page.getByRole('button', { name: 'Hide password', exact: true })
  await hide.focus(); await page.keyboard.press('Space')
  await expect(page.locator('#password')).toHaveAttribute('type', 'password')
  await expect(page.locator('.button-ripple')).toHaveCount(1)
  await expect(page.locator('#password')).toHaveValue('retained-input')
  await expect(page.locator('.button-ripple')).toHaveCount(0)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('#email')).toBeFocused()
  await expect(page.getByText('Enter your email address.', { exact: true })).toBeVisible()
})

test('reduced motion removes animation and ripples while controls keep working', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/sign-in')
  await expect(page.locator('.welcome-panel')).toHaveCSS('animation-name', 'none')
  await expect(page.locator('.form-panel')).toHaveCSS('animation-name', 'none')
  await page.getByRole('button', { name: 'Show password', exact: true }).click()
  await expect(page.locator('#password')).toHaveAttribute('type', 'text')
  await expect(page.locator('.button-ripple')).toHaveCount(0)
  await page.locator('#language').click()
  await expect(page.locator('#language-options')).toHaveCSS('animation-name', 'none')
  await page.getByRole('button', { name: 'አማርኛ', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'am')
  await expect(page.locator('#language')).toBeFocused()
})

