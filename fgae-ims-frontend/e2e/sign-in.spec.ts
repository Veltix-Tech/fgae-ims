import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { roles } from '../src/services/contracts/auth'
import { en } from '../src/i18n/locales/en/auth'
import { am } from '../src/i18n/locales/am/auth'

async function chooseLanguage(page: Page, locale: 'en' | 'am') {
  await page.locator('#language').click()
  await page.locator('#language-options').getByRole('button', { name: locale === 'en' ? 'English' : 'አማርኛ', exact: true }).click()
}

for (const locale of ['en', 'am'] as const) {
  const copy = locale === 'en' ? en : am
  for (const width of [360, 390, 768, 1024, 1440]) {
    test(`${locale} layout, accessibility and validation at ${width}px`, async ({ page }, testInfo) => {
      await page.setViewportSize({ width, height: 900 })
      await page.goto('/sign-in')
      await chooseLanguage(page, locale)
      await expect(page.getByRole('button', { name: copy.signIn, exact: true })).toBeVisible()
      await page.evaluate(() => document.fonts.ready)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
      await page.screenshot({ path: `docs/screenshots/sign-in-${locale}-${width}.png`, fullPage: true })
      await testInfo.attach('sign-in', { path: `docs/screenshots/sign-in-${locale}-${width}.png`, contentType: 'image/png' })
      await page.getByRole('button', { name: copy.signIn, exact: true }).click()
      await expect(page.locator('#email')).toBeFocused()
      await expect(page.getByText(copy.emailRequired, { exact: true })).toBeVisible()
      await page.locator('#email').fill('bad-email')
      await page.getByRole('button', { name: copy.signIn, exact: true }).click()
      await expect(page.getByText(copy.emailInvalid, { exact: true })).toBeVisible()
      await page.locator('#email').fill('volunteer@example.test')
      await page.locator('#password').fill('incorrect')
      await page.getByRole('button', { name: copy.showPassword, exact: true }).click()
      await expect(page.locator('#password')).toHaveAttribute('type', 'text')
      await page.getByRole('button', { name: copy.signIn, exact: true }).click()
      await expect(page.getByRole('alert')).toContainText(copy.INVALID_CREDENTIALS)
      await expect(page.getByRole('alert')).toBeFocused()
      await expect(page.locator('#password')).toHaveValue('incorrect')
      expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()).violations).toEqual([])
    })
  }
  for (const role of roles) {
    test(`${locale} ${role} sign-in, refresh and logout`, async ({ page }) => {
      await page.goto('/sign-in')
      await chooseLanguage(page, locale)
      await page.locator('#email').fill(`${role.toLowerCase().replaceAll('_', '.')}@example.test`)
      await page.locator('#password').fill('Demo-only-2026!')
      await page.getByRole('button', { name: copy.signIn, exact: true }).click()
      await expect(page.getByRole('heading', { name: copy.signedIn })).toBeFocused()
      await expect(page.locator('.role-list')).toContainText(copy[role])
      await expect(page).toHaveURL(/\/sign-in$/)
      await page.reload()
      await expect(page.getByRole('heading', { name: copy.signedIn })).toBeVisible()
      await expect(page.locator('html')).toHaveAttribute('lang', locale)
      await page.getByRole('button', { name: copy.signOut, exact: true }).click()
      await expect(page.locator('#password')).toHaveValue('')
      await page.reload()
      await expect(page.getByRole('button', { name: copy.signIn, exact: true })).toBeVisible()
    })
  }
  test(`${locale} pending, first login, inactive, expiry and offline retry`, async ({ page, context }) => {
    await page.goto('/sign-in')
    await chooseLanguage(page, locale)
    for (const [email, message] of [['pending@example.test', copy.application], ['first.login@example.test', copy.passwordChange]]) {
      await page.locator('#email').fill(email!)
      await page.locator('#password').fill('Demo-only-2026!')
      await page.getByRole('button', { name: copy.signIn, exact: true }).click()
      await expect(page.getByText(message!, { exact: true })).toBeVisible()
      await page.getByRole('button', { name: copy.signOut, exact: true }).click()
    }
    await page.locator('#email').fill('inactive@example.test')
    await page.locator('#password').fill('Demo-only-2026!')
    await page.getByRole('button', { name: copy.signIn, exact: true }).click()
    await expect(page.getByRole('alert')).toContainText(copy.INACTIVE_ACCOUNT)
    await page.evaluate(() => sessionStorage.setItem('fgae.synthetic.auth.v1', JSON.stringify({ version: 1, email: 'volunteer@example.test', expiresAt: 1 })))
    await page.reload()
    await expect(page.getByRole('alert')).toContainText(copy.SESSION_EXPIRED)
    await page.locator('#email').fill('volunteer@example.test')
    await page.locator('#password').fill('Demo-only-2026!')
    await context.setOffline(true)
    await page.getByRole('button', { name: copy.signIn, exact: true }).click()
    await expect(page.getByRole('alert')).toContainText(copy.NETWORK)
    await expect(page.locator('#password')).toHaveValue('Demo-only-2026!')
    await context.setOffline(false)
    await page.getByRole('button', { name: copy.signIn, exact: true }).click()
    await expect(page.getByRole('heading', { name: copy.signedIn })).toBeVisible()
  })
}

test('keyboard, protected URLs, locale persistence and reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/users/private-id')
  await expect(page).toHaveURL(/\/sign-in$/)
  await expect(page.getByText(en.sessionNotice)).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: en.skip })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: en.welcome })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.locator('#email')).toBeFocused()
  await page.keyboard.type('draft@example.test')
  await page.keyboard.press('Tab'); await page.keyboard.type('retained')
  await page.keyboard.press('Tab'); await page.keyboard.press('Space')
  await expect(page.locator('#password')).toHaveAttribute('type', 'text')
  await chooseLanguage(page, 'am')
  await expect(page.locator('#email')).toHaveValue('draft@example.test')
  await expect(page.locator('#password')).toHaveValue('retained')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', 'am')
  await expect(page.locator('#password')).toHaveValue('')
})

test('language accordion opens with keyboard, indicates selection and dismisses safely', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 900 })
  await page.goto('/sign-in')
  const trigger = page.locator('#language')
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('button', { name: 'English', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'docs/screenshots/language-accordion-360.png', fullPage: true, animations: 'disabled' })
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'English', exact: true })).toBeFocused()
  await page.keyboard.press('Tab'); await page.keyboard.press('Enter')
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('html')).toHaveAttribute('lang', 'am')
  expect(await page.locator('body').innerText()).not.toContain('።')
  await trigger.click(); await page.keyboard.press('Escape')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(trigger).toBeFocused()
  await trigger.click(); await page.locator('#email').click()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await page.setViewportSize({ width: 1440, height: 900 })
  await trigger.click()
  await page.screenshot({ path: 'docs/screenshots/language-accordion-1440.png', fullPage: true, animations: 'disabled' })
})

test('live responses: pending submission, retry, unknown role, logout; no synthetic fallback', async ({ page }) => {
  await page.route('**/auth/refresh', route => route.fulfill({ status: 401, json: { code: 'SESSION_EXPIRED' } }))
  await page.goto('http://127.0.0.1:5174/sign-in')
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  let calls = 0
  await page.route('**/auth/login', async route => { calls++; await gate; await route.fulfill({ status: 503, json: { code: 'UNAVAILABLE' } }) })
  await page.locator('#email').fill('volunteer@example.test')
  await page.locator('#password').fill('Demo-only-2026!')
  await page.getByRole('button', { name: en.signIn, exact: true }).click()
  await expect(page.getByRole('button', { name: en.signingIn, exact: true })).toBeDisabled()
  await expect.poll(() => calls).toBe(1)
  release()
  await expect(page.getByRole('alert')).toContainText(en.UNAVAILABLE)
  await expect(page.locator('#password')).toHaveValue('Demo-only-2026!')
  await page.route('**/auth/login', route => route.fulfill({ json: { success: true, data: { access_token: 'test-token' } } }))
  await page.route('**/auth/me', route => route.fulfill({ json: { success: true, data: { id: 'unknown-role', display_name: 'Fictional User', email: 'unknown@example.test', role_grants: [{ role: 'UNRECOGNIZED', scope: { kind: 'global', id: '*' } }], account_status: 'ACTIVE', must_change_password: false } } }))
  await page.getByRole('button', { name: en.signIn, exact: true }).click()
  await expect(page.getByText(en.noAccess, { exact: true })).toBeVisible()
  await page.route('**/auth/logout', route => route.fulfill({ status: 503, json: {} }))
  await page.getByRole('button', { name: en.signOut, exact: true }).click()
  await expect(page.getByRole('alert')).toContainText(en.logoutFailed)
  await page.route('**/auth/logout', route => route.fulfill({ json: { success: true, data: {} } }))
  await page.getByRole('button', { name: en.signOut, exact: true }).click()
  await expect(page.locator('#email')).toHaveValue('')
})
