test('registration saved draft keeps file blobs, excludes passwords and preserves language/unsaved decisions', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/register'); await documentsStep(page)
  await page.locator('#file-identity').setInputFiles(proof)
  await expect(page.getByRole('link', { name: en.regPreview })).toBeVisible()
  await page.getByRole('button', { name: en.regSaveDraft, exact: true }).click()
  await expect(page.getByRole('status')).toContainText(en.regSaved)
  page.once('dialog', dialog => dialog.accept()); await page.reload()
  await expect(page.getByRole('status')).toContainText(en.regRestored)
  await expect(page.getByRole('link', { name: en.regPreview })).toBeVisible()
  await page.getByRole('button', { name: en.regBack, exact: true }).click()
  await expect(page.locator('#reg-password')).toHaveValue('')
  await account(page)
  await page.locator('#language').click()
  await page.locator('#language-options').getByRole('button', { name: 'አማርኛ', exact: true }).click()
  await expect(page.locator('#reg-password')).toHaveValue(password)
  await expect(page.locator('.registration-step')).toHaveCSS('animation-name', 'none')
  await page.getByRole('link', { name: am.recoveryBack }).click()
  await expect(page.getByRole('heading', { name: am.regLeaveHeading })).toBeFocused()
  await page.getByRole('button', { name: am.resetKeepEditing }).click()
  await expect(page.locator('#reg-password')).toHaveValue(password)
  const stored = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('fgae.synthetic.registration.v1'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    return new Promise<string>(resolve => { const request = db.transaction('items').objectStore('items').get('draft'); request.onsuccess = () => { resolve(JSON.stringify(request.result)); db.close() } })
  })
  expect(stored).not.toContain(password)
  await page.getByRole('link', { name: am.recoveryBack }).click()
  await page.getByRole('button', { name: am.regLeaveConfirm }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
})
test('registration draft conflict preserves edits, reload resolves and delete clears saved progress', async ({ page, context }) => {
  await page.goto('/register'); await details(page)
  await page.getByRole('button', { name: en.regSaveDraft, exact: true }).click()
  await expect(page.getByRole('status')).toContainText(en.regSaved)
  const other = await context.newPage(); await other.goto('/register')
  await other.locator('#reg-fullName').fill('Another saved name')
  await other.getByRole('button', { name: en.regSaveDraft, exact: true }).click()
  await expect(other.getByRole('status')).toContainText(en.regSaved)
  await page.bringToFront()
  await page.locator('#reg-fullName').fill('My unsaved name')
  await page.getByRole('button', { name: en.regSaveDraft, exact: true }).click()
  await expect(page.getByRole('alert')).toContainText(en.regConflict)
  await expect(page.locator('#reg-fullName')).toHaveValue('My unsaved name')
  await page.getByRole('button', { name: en.regReload, exact: true }).click()
  await page.locator('.leave-confirmation').getByRole('button', { name: en.regReload, exact: true }).click()
  await expect(page.locator('#reg-fullName')).toHaveValue('Another saved name')
  await page.getByRole('button', { name: en.regDiscardDraft }).click()
  await page.getByRole('button', { name: en.regDeleteConfirm }).click()
  await expect(page.locator('#reg-fullName')).toHaveValue('')
  await page.reload(); await expect(page.locator('#reg-fullName')).toHaveValue('')
})
