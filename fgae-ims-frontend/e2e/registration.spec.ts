test('live registration config retry, empty branches, upload cancel/retry and idempotent submit', async ({ page }) => {
  await page.route('**/volunteers/registration/config', route => route.fulfill({ status: 503, json: {} }))
  await page.route('**/volunteers/registration/draft', route => route.fulfill({ json: { success: true, data: null } }))
  await page.goto('http://127.0.0.1:5174/register')
  await expect(page.getByRole('alert')).toContainText(en.regUnavailable)
  await page.route('**/volunteers/registration/config', route => route.fulfill({ json: { success: true, data: { ...registrationConfig, branches: [] } } }))
  await page.getByRole('button', { name: en.resetRetry, exact: true }).click()
  await expect(page.getByText(en.regEmptyBranches)).toBeVisible()
  await page.route('**/volunteers/registration/config', route => route.fulfill({ json: { success: true, data: registrationConfig } }))
  await page.getByRole('button', { name: en.resetRetry, exact: true }).click()
  await documentsStep(page)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const doc = { id: 'test-document', typeId: 'identity', name: proof.name, mime: proof.mimeType, size: png.length }
  await page.route('**/volunteers/registration/documents', async route => { await gate; await route.fulfill({ json: { success: true, data: doc } }).catch(() => {}) })
  await page.locator('#file-identity').setInputFiles(proof)
  await expect(page.getByRole('button', { name: en.regNext, exact: true })).toBeDisabled()
  await page.getByRole('button', { name: en.regCancelUpload }).click()
  await expect(page.getByRole('alert')).toContainText(en.regUploadCancelled)
  release()
  await page.route('**/volunteers/registration/documents', route => route.fulfill({ json: { success: true, data: doc } }))
  await page.route('**/volunteers/registration/documents/test-document/content', route => route.fulfill({ contentType: 'image/png', body: png }))
  await page.getByRole('button', { name: en.resetRetry, exact: true }).click()
  await expect(page.getByRole('link', { name: en.regPreview })).toBeVisible()
  await page.getByRole('button', { name: en.regNext, exact: true }).click()
  await page.locator('#reg-confirmed').check()
  const keys: string[] = []
  await page.route('**/volunteers/applications', async route => { keys.push(route.request().headers()['idempotency-key']!); await route.fulfill({ status: 503, json: {} }) })
  await page.getByRole('button', { name: en.regSubmit }).click()
  await expect(page.getByRole('alert')).toContainText(en.regUnavailable)
  await page.route('**/volunteers/applications', async route => {
    keys.push(route.request().headers()['idempotency-key']!)
    await route.fulfill({ json: { success: true, data: { id: 'APP-TEST', email, submittedAt: new Date().toISOString(), status: 'PENDING' } } })
  })
  await page.getByRole('button', { name: en.regSubmit }).click()
  await expect(page.getByRole('heading', { name: en.regSuccessHeading })).toBeVisible()
  expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1])
  expect(await page.evaluate(() => localStorage.getItem('fgae.synthetic.credentials.v1'))).toBeNull()
})
