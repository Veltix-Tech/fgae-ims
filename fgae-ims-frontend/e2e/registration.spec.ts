async function account(page: Page) {
  await page.locator('#reg-password').fill(password)
  await page.locator('#reg-confirmation').fill(password)
}
async function documentsStep(page: Page, copy = en) {
  await details(page); await page.getByRole('button', { name: copy.regNext, exact: true }).click()
  await account(page); await page.getByRole('button', { name: copy.regNext, exact: true }).click()
}
